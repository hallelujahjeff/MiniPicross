/** 解析一个模型的 layers，返回体素数组 [{x,y,z,c}]（c = palette 索引） */
export function parseVoxels(model) {
  const voxels = [];
  const [W, H, D] = model.size;
  for (let y = 0; y < H; y++) {
    const rows = model.layers[y];
    for (let z = 0; z < D; z++) {
      const row = rows[z];
      for (let x = 0; x < W; x++) {
        const ch = row[x];
        if (ch === "." || ch === " ") continue;
        const c = ch === "#" ? 0 : ch.charCodeAt(0) - 48 - 1;
        voxels.push({ x, y, z, c: Math.max(0, Math.min(8, c)) });
      }
    }
  }
  return voxels;
}
